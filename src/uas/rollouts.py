"""Episode collection helpers for agents and random baselines."""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path
from typing import Any

import numpy as np

from uas.envs import (
    ACTION_SCHEMA,
    ENVIRONMENT_ID,
    OBSERVATION_SCHEMA,
    TASK_FAMILY,
    ContinuousWorldEnv,
)
from uas.memory import EpisodeRecord, MemoryStore, Trajectory

ActionProvider = Callable[[np.ndarray], np.ndarray]


def run_episode(
    environment: ContinuousWorldEnv,
    action_provider: ActionProvider,
    *,
    seed: int,
) -> tuple[Trajectory, dict[str, Any]]:
    """Run one complete episode and return its transitions and summary."""
    observation, info = environment.reset(seed=seed)
    observations = [observation.copy()]
    actions: list[np.ndarray] = []
    rewards: list[float] = []
    terminated_flags: list[bool] = []
    truncated_flags: list[bool] = []
    total_reward = 0.0

    while True:
        action = np.asarray(action_provider(observation), dtype=np.float32)
        next_observation, reward, terminated, truncated, info = environment.step(
            action
        )
        actions.append(action.copy())
        rewards.append(float(reward))
        terminated_flags.append(bool(terminated))
        truncated_flags.append(bool(truncated))
        observations.append(next_observation.copy())
        total_reward += float(reward)
        observation = next_observation
        if terminated or truncated:
            break

    trajectory = Trajectory(
        observations=np.asarray(observations, dtype=np.float32),
        actions=np.asarray(actions, dtype=np.float32),
        rewards=np.asarray(rewards, dtype=np.float32),
        terminated=np.asarray(terminated_flags, dtype=np.bool_),
        truncated=np.asarray(truncated_flags, dtype=np.bool_),
    )
    summary = {
        **info,
        "total_reward": total_reward,
        "steps": len(actions),
        "termination_reason": "success" if info["success"] else "time_limit",
    }
    return trajectory, summary


def store_episode(
    store: MemoryStore,
    environment: ContinuousWorldEnv,
    trajectory: Trajectory,
    summary: dict[str, Any],
    *,
    seed: int,
    agent_id: str,
    policy_version: str,
    policy_reference: str | Path | None = None,
) -> EpisodeRecord:
    """Create a structured record and atomically add its trajectory."""
    success = bool(summary["success"])
    if success:
        normalized_score = 1.0
    else:
        normalized_score = min(0.49, max(0.0, 1.0 - float(summary["distance"])))
    record = EpisodeRecord.create(
        environment_id=ENVIRONMENT_ID,
        task_id=environment.task_id,
        task_family=TASK_FAMILY,
        task_description=environment.task.description,
        observation_schema=OBSERVATION_SCHEMA,
        action_schema=ACTION_SCHEMA,
        agent_id=agent_id,
        policy_version=policy_version,
        policy_reference=(None if policy_reference is None else str(policy_reference)),
        seed=seed,
        success=success,
        total_reward=float(summary["total_reward"]),
        normalized_score=normalized_score,
        steps=int(summary["steps"]),
        termination_reason=str(summary["termination_reason"]),
        collision_count=int(summary["collision_count"]),
        task_vector=tuple(float(value) for value in environment.task_vector),
    )
    store.add_episode(record, trajectory)
    return record


def collect_random_episodes(
    store: MemoryStore,
    environment: ContinuousWorldEnv,
    *,
    count: int,
    seed_start: int,
) -> list[EpisodeRecord]:
    """Store exploratory episodes so naive sharing includes poor experience."""
    records: list[EpisodeRecord] = []
    for index in range(count):
        seed = seed_start + index
        random = np.random.default_rng(seed)
        trajectory, summary = run_episode(
            environment,
            lambda _observation, random=random: random.uniform(
                -1.0, 1.0, size=2
            ).astype(np.float32),
            seed=seed,
        )
        records.append(
            store_episode(
                store,
                environment,
                trajectory,
                summary,
                seed=seed,
                agent_id="random-explorer",
                policy_version="random-v1",
            )
        )
    return records

def collect_policy_episodes(
    store: MemoryStore,
    environment: ContinuousWorldEnv,
    model: Any,
    *,
    count: int,
    seed_start: int,
    policy_reference: str | Path,
) -> list[EpisodeRecord]:
    """Store deterministic episodes generated by a trained SB3 policy."""
    records: list[EpisodeRecord] = []
    for index in range(count):
        seed = seed_start + index

        def predict(observation: np.ndarray) -> np.ndarray:
            action, _ = model.predict(observation, deterministic=True)
            return np.asarray(action, dtype=np.float32)

        trajectory, summary = run_episode(environment, predict, seed=seed)
        records.append(
            store_episode(
                store,
                environment,
                trajectory,
                summary,
                seed=seed,
                agent_id=f"sac-{environment.task_id}",
                policy_version="sac-v1",
                policy_reference=policy_reference,
            )
        )
    return records
